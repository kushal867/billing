import { AlertTriangle } from "lucide-react";
import { Amt } from "@/components/amount";
import { EmptyState } from "@/components/ui/states";
import { MONEY_META, type ReportDoc } from "@/lib/services/report-doc";
import { formatAmount } from "@/lib/format";
import { cn } from "@/lib/utils";

/** HTML/print rendering of a ReportDoc. The PDF/Excel/CSV exports are produced from the same object. */
export function ReportView({ doc }: { doc: ReportDoc }) {
  return (
    <article className="print-area rounded-lg border bg-white p-5 shadow-sm">
      <header className="mb-4 border-b pb-3">
        <h2 className="text-lg font-semibold text-navy">{doc.business.name}</h2>
        <p className="text-xs text-muted-foreground">{[doc.business.address, doc.business.phone, doc.business.email, doc.business.pan && `PAN ${doc.business.pan}`].filter(Boolean).join("  |  ")}</p>
        {doc.business.header && <p className="text-xs text-muted-foreground">{doc.business.header}</p>}
        <h3 className="mt-3 text-base font-semibold">{doc.title}</h3>
        <p className="text-sm text-muted-foreground">{doc.subtitle}</p>
      </header>

      {doc.warnings.map((w) => (
        <p key={w} className="mb-3 flex gap-2 rounded-md border border-amber-300 bg-amber-50 p-2.5 text-sm text-amber-900"><AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden />{w}</p>
      ))}

      {doc.meta.length > 0 && (
        <dl className="mb-5 grid gap-x-6 gap-y-1.5 text-sm sm:grid-cols-2 lg:grid-cols-3">
          {doc.meta.map(([k, v]) => (
            <div key={k} className="flex justify-between gap-3 border-b border-dashed py-1">
              <dt className="text-muted-foreground">{k}</dt>
              <dd className="text-right font-medium">{MONEY_META.has(k) ? <Amt v={v} grouping={doc.grouping} tone={k === "Net Profit" ? "income" : k === "Net Loss" ? "expense" : "plain"} /> : v}</dd>
            </div>
          ))}
        </dl>
      )}

      {doc.sections.map((s, i) => (
        <section key={i} className="mb-6">
          {s.heading && <h4 className="mb-2 font-semibold text-navy">{s.heading}</h4>}
          <div className="overflow-x-auto rounded-md border">
            <table className="tbl">
              <thead>
                <tr>{s.columns.map((c) => <th key={c.key} className={cn(c.align === "right" && "text-right")}>{c.label}</th>)}</tr>
              </thead>
              <tbody>
                {s.rows.map((r, ri) => (
                  <tr key={ri}>
                    {s.columns.map((c) => (
                      <td key={c.key} className={cn(c.align === "right" && "r")}>
                        {c.type === "money" ? <Amt v={r[c.key]} grouping={doc.grouping} className={c.key === "balance" || c.key === "closing" ? "font-medium" : ""} /> : r[c.key]}
                      </td>
                    ))}
                  </tr>
                ))}
                {s.rows.length === 0 && (
                  <tr><td colSpan={s.columns.length}><EmptyState title={s.emptyMessage ?? "No records"} /></td></tr>
                )}
              </tbody>
              {s.totals && (
                <tfoot>
                  <tr className="border-t-2 bg-muted/60 font-semibold">
                    {s.columns.map((c) => (
                      <td key={c.key} className={cn("border-t px-3 py-2", c.align === "right" && "r")}>
                        {c.type === "money" && s.totals![c.key] ? formatAmount(s.totals![c.key], doc.grouping) : s.totals![c.key]}
                      </td>
                    ))}
                  </tr>
                </tfoot>
              )}
            </table>
          </div>
        </section>
      ))}

      {doc.notes.map((n) => <p key={n} className="mb-1 text-xs text-muted-foreground">{n}</p>)}
      {doc.business.footer && <p className="mt-3 text-xs text-muted-foreground">{doc.business.footer}</p>}
      <p className="mt-4 text-[11px] text-muted-foreground">Generated by KusBill on {doc.generatedAt}</p>
    </article>
  );
}
